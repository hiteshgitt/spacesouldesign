"use client";

import dynamic from "next/dynamic";
import Image from "next/image";
import { useEffect, useRef, useState } from "react";
import { gsap } from "@/lib/gsap";
import { createDrive } from "@/components/three/BoothScene";
import { useCanUse3D } from "@/lib/webgl";
import type { Project } from "@/content/types";
import Placeholder from "@/components/ui/Placeholder";

const SceneCanvas = dynamic(() => import("@/components/three/SceneCanvas"), { ssr: false });

const STATES = ["Blueprint", "Concept", "Reality"] as const;

/**
 * Case-study visualization. Stills by default (fast, works everywhere); on
 * capable desktops the visitor can opt in to the live model and drag to orbit.
 */
export default function ProjectViewer({ project }: { project: Project }) {
  const [state, setState] = useState(2);
  const capable = useCanUse3D();
  const [live, setLive] = useState(false);
  const [ready, setReady] = useState(false);
  const [drive] = useState(() => createDrive({ state: 2, assembly: 1 }));
  const stage = useRef<HTMLDivElement>(null);

  useEffect(() => {
    gsap.to(drive, { state, duration: 1.2, ease: "power2.inOut", overwrite: true });
  }, [state, drive]);

  // Drag to orbit the live model.
  useEffect(() => {
    const el = stage.current;
    if (!live || !el) return;
    let startX = 0;
    let startOrbit = 0;
    const down = (e: PointerEvent) => {
      startX = e.clientX;
      startOrbit = drive.orbit;
      el.setPointerCapture(e.pointerId);
      el.addEventListener("pointermove", move);
    };
    const move = (e: PointerEvent) => {
      drive.orbit = startOrbit + ((e.clientX - startX) / el.clientWidth) * Math.PI;
    };
    const up = () => el.removeEventListener("pointermove", move);
    el.addEventListener("pointerdown", down);
    el.addEventListener("pointerup", up);
    el.addEventListener("pointercancel", up);
    return () => {
      el.removeEventListener("pointerdown", down);
      el.removeEventListener("pointerup", up);
      el.removeEventListener("pointercancel", up);
      el.removeEventListener("pointermove", move);
    };
  }, [live, drive]);

  const stills = [project.stages.blueprint, project.stages.concept, project.stages.reality];

  return (
    <div>
      <div
        ref={stage}
        className={`relative aspect-[4/3] w-full overflow-hidden bg-void md:aspect-[16/9] ${live ? "cursor-grab active:cursor-grabbing" : ""}`}
      >
        {stills.map((img, i) => (
          <Image
            key={i}
            src={img.src}
            alt={i === state && !ready ? img.alt : ""}
            fill
            sizes="(min-width: 1024px) 85vw, 100vw"
            className={`object-cover transition-opacity duration-700 ${i === state && !ready ? "opacity-100" : "opacity-0"}`}
          />
        ))}
        {live && (
          <div className={`absolute inset-0 transition-opacity duration-1000 ${ready ? "opacity-100" : "opacity-0"}`} aria-hidden>
            <SceneCanvas drive={drive} slug={project.slug} shot="cover" dust={false} onReady={() => setReady(true)} />
          </div>
        )}
        <div className="pointer-events-none absolute inset-4 flex flex-col justify-between text-ivory/60 md:inset-6" aria-hidden>
          <div className="flex justify-between">
            <span className="reg-mark" />
            <span className="t-mono">{STATES[state]}</span>
            <span className="reg-mark" />
          </div>
          <div className="flex items-end justify-between">
            <span className="reg-mark" />
            {live && ready && <span className="t-mono">Drag to orbit</span>}
            <span className="reg-mark" />
          </div>
        </div>
      </div>

      <div className="mt-6 flex flex-wrap items-center justify-between gap-4">
        <div role="group" aria-label="Visualization stage" className="flex gap-2">
          {STATES.map((label, i) => (
            <button
              key={label}
              type="button"
              aria-pressed={state === i}
              onClick={() => setState(i)}
              className="chip text-ivory"
            >
              {String(i + 1).padStart(2, "0")} {label}
            </button>
          ))}
        </div>
        <div className="flex items-center gap-4">
          {project.placeholder && <Placeholder title="Generated by the site's procedural booth model">Sample model</Placeholder>}
          {capable && !live && (
            <button type="button" className="btn btn-ghost" onClick={() => setLive(true)}>
              Load interactive 3D
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
